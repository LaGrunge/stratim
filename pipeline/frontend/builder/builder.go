// PipelineBuilder Takes the yaml configs and some metadata and returns the internal data model to execute a pipeline.
type PipelineBuilder struct {
	Yamls               []*YamlFile
	Envs                map[string]string
	AdditionalEnvs      map[string]string
	DefaultLabels       map[string]string
	RepoTrusted         *metadata.TrustedConfiguration
	TrustedClonePlugins []string
	PrivilegedPlugins   []string
	CompilerOptions     []compiler.Option
	GetWorkflowMetadata func(workflow *Workflow) metadata.Metadata
	// SelectedWorkflow, if set, limits to this workflow and its hard dependencies.
	SelectedWorkflow string
	// RunSelected: the selected workflow and its dependencies run whatever
	// the when of each says; a cron the workflow declares runs it so.
	RunSelected bool
	// ListOnly reports the workflows that could run instead of building them.
	ListOnly bool
}

func (b *PipelineBuilder) Build() (items []*Item, errorsAndWarnings error) {
	return b.build(newBuildState())
}

// build is Build keeping what it reads in state.
func (b *PipelineBuilder) build(state *buildState) (items []*Item, errorsAndWarnings error) {
	expanded, err := jsonnet.ExpandWith(b.Yamls, b.AdditionalEnvs)
	if err != nil {
		return nil, &pipeline_errors.PipelineError{Type: pipeline_errors.PipelineErrorTypeCompiler, Message: err.Error()}
	}
	b.Yamls = SortYamlFilesByName(expanded)

	yamls := b.Yamls
	selected := SanitizePath(b.SelectedWorkflow)
	if b.SelectedWorkflow != "" {
		var err error
		yamls, err = b.selectYamls(state, selected)
		if err != nil {
			return nil, err
		}
		if len(yamls) == 0 {
			return nil, &pipeline_errors.PipelineError{
				Type:    pipeline_errors.PipelineErrorTypeGeneric,
				Message: fmt.Sprintf("selected workflow '%s' does not exist", b.SelectedWorkflow),
			}
		}
	}

	pidSequence := 1

	for _, y := range yamls {
		// matrix axes
		axes, err := state.source(y).matrix()
		if err != nil {
			return nil, err
		}
		if len(axes) == 0 {
			axes = append(axes, matrix.Axis{})
		}

		for i, axis := range axes {
			workflow := &Workflow{
				PID:     pidSequence,
				Environ: axis,
				Name:    SanitizePath(y.Name),
			}
			if len(axes) > 1 {
				workflow.AxisID = i + 1
			}
			item, err := b.genItemForWorkflow(state, workflow, axis, y)
			if err != nil && pipeline_errors.HasBlockingErrors(err) {
				return nil, err
			} else if err != nil {
				errorsAndWarnings = multierr.Append(errorsAndWarnings, state.reportOnce(y.Name, err))
			}

			if item == nil {
				continue
			}
			items = append(items, item)
			pidSequence++
		}
		state.done(y, SanitizePath(y.Name))

		// TODO: add summary workflow that send status back based on workflows generated by matrix function
		// depend on https://github.com/woodpecker-ci/woodpecker/issues/778
	}

	items = filterMissingDependencies(items)

	if b.SelectedWorkflow != "" && !ContainsItemWithName(selected, items) {
		return nil, multierr.Append(errorsAndWarnings, &pipeline_errors.PipelineError{
			Type:    pipeline_errors.PipelineErrorTypeGeneric,
			Message: fmt.Sprintf("selected workflow '%s' does not match its conditions or misses a dependency", b.SelectedWorkflow),
		})
	}

	return items, errorsAndWarnings
}

func (b *PipelineBuilder) genItemForWorkflow(state *buildState, workflow *Workflow, axis matrix.Axis, file *YamlFile) (item *Item, errorsAndWarnings error) {
	workflowMetadata := b.GetWorkflowMetadata(workflow)
	config, err := b.parseWorkflow(state.source(file), axis, workflowMetadata)
	if err != nil {
		return nil, multierr.Append(errorsAndWarnings, err)
	}
	parsed, environ, params, invalidParams := config.parsed, config.environ, config.params, config.invalidParams

	// lint pipeline
	if !b.ListOnly {
		errorsAndWarnings = multierr.Append(errorsAndWarnings, linter.New(
			linter.WithTrusted(linter.TrustedConfiguration{
				Network:  b.RepoTrusted.Network,
				Volumes:  b.RepoTrusted.Volumes,
				Security: b.RepoTrusted.Security,
			}),
			linter.PrivilegedPlugins(b.PrivilegedPlugins),
			linter.WithTrustedClonePlugins(b.TrustedClonePlugins),
			linter.WithVariables(environ),
			linter.WithCache(state.lintCache()),
		).Lint([]*linter.WorkflowConfig{{
			Workflow:  parsed,
			File:      workflow.Name,
			RawConfig: string(file.Data),
		}}))
		if pipeline_errors.HasBlockingErrors(errorsAndWarnings) {
			return nil, errorsAndWarnings
		}
	}

	// checking if filtered.
	whenMatch := parsed.When.Match
	if b.ListOnly {
		whenMatch = parsed.When.MatchIgnoringEvaluate
	}
	if b.RunSelected && b.SelectedWorkflow != "" {
		// only the selected workflow and its dependencies are read: they run
		// whatever started the pipeline, here and for the compiler; their
		// status, matrix and platform conditions, and the when of their
		// steps, hold
		parsed.When = parsed.When.WithoutTrigger()
		whenMatch = parsed.When.Match
	}
	if match, err := whenMatch(workflowMetadata, true, environ); !match && err == nil {
		log.Debug().Str("pipeline", workflow.Name).Msg(
			"marked as skipped, does not match metadata",
		)
		return nil, nil
	} else if err != nil {
		log.Debug().Str("pipeline", workflow.Name).Msg(
			"pipeline config could not be parsed",
		)
		return nil, multierr.Append(errorsAndWarnings, err)
	}

	// a parameter's options matter to a workflow that runs; listing the
	// workflows of a manual run, none is given yet
	if invalidParams != nil {
		if !b.ListOnly {
			return nil, multierr.Append(errorsAndWarnings, invalidParams)
		}
		if warning, ok := errors.AsType[*pipeline_errors.PipelineError](invalidParams); ok {
			warning.IsWarning = true
		}
		errorsAndWarnings = multierr.Append(errorsAndWarnings, invalidParams)
	}

	var ir *backend_types.Config
	if !b.ListOnly {
		ir, err = b.toInternalRepresentation(parsed, axis, params, workflowMetadata, workflow.ID)
		if err != nil {
			return nil, multierr.Append(errorsAndWarnings, err)
		}

		if len(ir.Stages) == 0 {
			return nil, nil
		}
	}

	item = &Item{
		Workflow:         workflow,
		Config:           ir,
		Labels:           parsed.Labels,
		DependsOn:        parsed.DependsOn,
		ConcurrencyLimit: parsed.Concurrency.Limit,
		ConcurrencyGroup: parsed.Concurrency.Group,
		Priority:         parsed.Priority,
		Timeout:          time.Duration(parsed.Timeout),
		// TODO: remove in next major.
		RunsOn: parsed.RunsOn, //nolint:staticcheck
	}
	if len(item.Labels) == 0 {
		item.Labels = make(map[string]string, len(b.DefaultLabels))
		// Set default labels if no labels are defined in the pipeline
		maps.Copy(item.Labels, b.DefaultLabels)
	}

	if len(item.RunsOn) == 0 {
		statuses, unfiltered := parsed.When.MatchingStatuses(workflowMetadata, true, environ)
		item.RunsOn = statuses
		if unfiltered && !slices.Contains(statuses, pipeline.StatusSuccess) {
			item.RunsOn = append(item.RunsOn, pipeline.StatusSuccess)
		}
	}

	// "woodpecker-ci.org" namespace is reserved for internal use — drop any
	// user-defined labels that try to use it.
	for key := range item.Labels {
		if strings.HasPrefix(key, pipeline.InternalLabelPrefix) {
			log.Debug().Str("label", key).Msg("dropped pipeline label with reserved prefix woodpecker-ci.org")
			delete(item.Labels, key)
		}
	}

	// Stamp Woodpecker-managed internal labels onto the item so that the server
	// and backends can use them for routing, observability, etc.
	item.Labels[pipeline.LabelForgeRemoteID] = workflowMetadata.Forge.Type
	item.Labels[pipeline.LabelRepoForgeID] = workflowMetadata.Repo.RemoteID
	item.Labels[pipeline.LabelRepoID] = strconv.FormatInt(workflowMetadata.Repo.ID, 10)
	item.Labels[pipeline.LabelRepoName] = workflowMetadata.Repo.Name
	item.Labels[pipeline.LabelRepoFullName] = workflowMetadata.Repo.Owner + "/" + workflowMetadata.Repo.Name
	item.Labels[pipeline.LabelBranch] = workflowMetadata.Repo.Branch
	item.Labels[pipeline.LabelOrgID] = strconv.FormatInt(workflowMetadata.Repo.OrgID, 10)
	item.Labels[pipeline.LabelCommitBranch] = workflowMetadata.Curr.Commit.Branch
	item.Labels[pipeline.LabelEvent] = string(workflowMetadata.Curr.Event)

	return item, errorsAndWarnings
}

func (b *PipelineBuilder) environmentVariables(metadata metadata.Metadata, axis matrix.Axis) map[string]string {
	environ := metadata.Environ()
	maps.Copy(environ, axis)

	// add additional environment variables for substituting
	for k, v := range b.AdditionalEnvs {
		if _, exists := environ[k]; exists {
			// don't override existing values
			continue
		}
		environ[k] = v
	}

	// add global environment variables for substituting
	for k, v := range b.Envs {
		if _, exists := environ[k]; exists {
			// don't override existing values
			continue
		}
		environ[k] = v
	}

	return environ
}

func (b *PipelineBuilder) toInternalRepresentation(parsed *yaml_types.Workflow, axis, params map[string]string, metadata metadata.Metadata, workflowID int64) (*backend_types.Config, error) {
	// a parameter has one value: plugins, which get no parameters, do not
	// get a global variable of its name either
	envs := maps.Clone(b.Envs)
	for name := range params {
		delete(envs, name)
	}

	options := []compiler.Option{}
	options = append(
		options,
		compiler.WithNonPluginEnviron(axis),
		compiler.WithNonPluginEnviron(b.AdditionalEnvs),
		compiler.WithNonPluginEnviron(params),
		compiler.WithEnviron(envs),
		compiler.WithEscalated(b.PrivilegedPlugins...),
		compiler.WithTrustedClonePlugins(b.TrustedClonePlugins),
		compiler.WithPrefix(
			fmt.Sprintf(
				"wp_%s_%d",
				strings.ToLower(ulid.Make().String()),
				workflowID,
			),
		),
		compiler.WithMetadata(metadata),
		compiler.WithTrustedSecurity(b.RepoTrusted.Security),
	)

	// by adding the passed in options last, we allow them
	// to override any of the default options set above
	options = append(options, b.CompilerOptions...)

	return compiler.New(options...).Compile(parsed)
}
